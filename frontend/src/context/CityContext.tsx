export type CityData = CityConfig;
export type LocalityItem = Locality;
export const DEFAULT_CITIES = SUPPORTED_CITIES;

interface CityContextType {
  selectedCity: CityConfig;
  setSelectedCity: (city: CityConfig) => void;
  allCities: CityConfig[];
  selectedLocality: string | null;
  setSelectedLocality: (locality: string | null) => void;
  currentCity: string;
  setCity: (cityName: string) => void;
  cityData: CityConfig;
  availableCities: CityConfig[];
  loadingCities: boolean;
}

const CityContext = createContext<CityContextType | undefined>(undefined);

export const CityProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [selectedCity, setSelectedCityState] = useState<CityConfig>(() => {
    const saved = localStorage.getItem('needradar_selected_city');
    if (saved) {
      const match = SUPPORTED_CITIES.find(c => c.name.toLowerCase() === saved.toLowerCase());
      if (match) return match;
    }
    return SUPPORTED_CITIES.find(c => c.name === 'Bengaluru') || SUPPORTED_CITIES[0];
  });

  const [selectedLocality, setSelectedLocality] = useState<string | null>(null);

  const setSelectedCity = (city: CityConfig) => {
    setSelectedCityState(city);
    setSelectedLocality(null);
    localStorage.setItem('needradar_selected_city', city.name);
  };

  const setCity = (cityName: string) => {
    const match = SUPPORTED_CITIES.find(c => c.name.toLowerCase() === cityName.toLowerCase());
    if (match) {
      setSelectedCity(match);
    }
  };

  useEffect(() => {
    const saved = localStorage.getItem('needradar_selected_city');
    if (saved && saved !== selectedCity.name) {
      const match = SUPPORTED_CITIES.find(c => c.name.toLowerCase() === saved.toLowerCase());
      if (match) setSelectedCityState(match);
    }
  }, []);

  return (
    <CityContext.Provider
      value={{
        selectedCity,
        setSelectedCity,
        allCities: SUPPORTED_CITIES,
        selectedLocality,
        setSelectedLocality,
        currentCity: selectedCity.name,
        setCity,
        cityData: selectedCity,
        availableCities: SUPPORTED_CITIES,
        loadingCities: false,
      }}
    >
      {children}
    </CityContext.Provider>
  );
};

export const useCity = () => {
  const context = useContext(CityContext);
  if (!context) {
    throw new Error('useCity must be used within a CityProvider');
  }
  return context;
};
